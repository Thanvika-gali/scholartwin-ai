import React, { useState } from 'react';
import Card, { CardHeader, CardTitle, CardContent } from '../ui/Card';
import Button from '../ui/Button';
import Badge from '../ui/Badge';
import { getImportanceBadgeStyle } from '../../utils/intelligenceValidation';

export default function PersonalizedInsightsTab({
  insights,
  isLoading,
  onRefreshInsights,
  onDismissInsight,
  onNavigateTab,
}) {
  const [selectedCategory, setSelectedCategory] = useState('ALL');

  const categories = [
    { value: 'ALL', label: 'All Insights' },
    { value: 'LEARNING', label: 'Learning' },
    { value: 'DSA', label: 'DSA Tracking' },
    { value: 'CAREER', label: 'Career Readiness' },
    { value: 'KNOWLEDGE', label: 'Knowledge Vault' },
    { value: 'PRODUCTIVITY', label: 'Productivity' },
  ];

  const filtered = insights.filter((i) => {
    if (selectedCategory !== 'ALL' && i.category !== selectedCategory) {
      return false;
    }
    return i.status === 'ACTIVE';
  });

  return (
    <div className="space-y-6">
      {/* Top Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 bg-bg-surface border border-border-default rounded-2xl p-5 shadow-sm">
        <div>
          <h2 className="text-lg font-bold text-text-primary tracking-tight">Personalized Academic Insights</h2>
          <p className="text-xs text-text-muted mt-0.5">
            Real-time intelligence generated by synthesizing your actual performance across courses, DSA problems, and career goals.
          </p>
        </div>

        <Button variant="primary" size="sm" onClick={onRefreshInsights} loading={isLoading}>
          ↻ Refresh Insights
        </Button>
      </div>

      {/* Category Pills */}
      <div className="flex flex-wrap gap-1.5">
        {categories.map((c) => {
          const count = c.value === 'ALL'
            ? insights.filter((i) => i.status === 'ACTIVE').length
            : insights.filter((i) => i.category === c.value && i.status === 'ACTIVE').length;

          return (
            <button
              key={c.value}
              onClick={() => setSelectedCategory(c.value)}
              className={`px-3 py-1.5 rounded-xl text-xs font-semibold transition-colors flex items-center gap-1.5 ${
                selectedCategory === c.value
                  ? 'bg-brand-teal text-white shadow-sm'
                  : 'bg-bg-surface border border-border-default text-text-secondary hover:text-text-primary'
              }`}
            >
              <span>{c.label}</span>
              <span className="text-[10px] opacity-75 font-mono">({count})</span>
            </button>
          );
        })}
      </div>

      {/* Insights List */}
      {isLoading ? (
        <div className="py-16 text-center text-xs text-text-muted">Analyzing cross-module academic telemetry...</div>
      ) : filtered.length === 0 ? (
        <Card className="py-12 text-center space-y-3">
          <div className="w-12 h-12 rounded-2xl bg-brand-gold/15 text-brand-gold flex items-center justify-center mx-auto text-xl font-bold">
            💡
          </div>
          <h3 className="text-sm font-bold text-text-primary">No active insights in this category</h3>
          <p className="text-xs text-text-muted max-w-md mx-auto">
            Click "Refresh Insights" to evaluate your current problem attempts, roadmap completion, and knowledge notes.
          </p>
          <Button variant="outline" size="sm" onClick={onRefreshInsights}>
            Generate Insights
          </Button>
        </Card>
      ) : (
        <div className="space-y-4">
          {filtered.map((item) => {
            const importanceStyle = getImportanceBadgeStyle(item.importance);

            return (
              <Card key={item.id} className="hover:border-brand-teal/40 transition-all">
                <CardContent className="p-5 sm:p-6 space-y-4">
                  {/* Title & Header Badges */}
                  <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2.5">
                    <div className="space-y-1">
                      <div className="flex items-center gap-2 flex-wrap">
                        <span className="text-[10px] font-bold px-2 py-0.5 rounded-md bg-brand-teal/15 text-brand-teal dark:text-brand-teal-light border border-brand-teal/30">
                          {item.category}
                        </span>
                        <span className={`text-[10px] font-semibold px-2 py-0.5 rounded-md border ${importanceStyle}`}>
                          {item.importance} Priority
                        </span>
                        <span className="text-[10px] text-text-muted font-mono">
                          Confidence: {Math.round((item.confidence || 0.85) * 100)}%
                        </span>
                      </div>
                      <h3 className="text-base font-bold text-text-primary tracking-tight">
                        {item.title}
                      </h3>
                    </div>

                    <button
                      onClick={() => onDismissInsight(item.id)}
                      className="self-start sm:self-auto text-xs px-2.5 py-1 rounded-lg border border-border-default text-text-muted hover:text-text-primary hover:bg-bg-surface-hover transition-colors"
                      title="Dismiss this insight"
                    >
                      Dismiss
                    </button>
                  </div>

                  {/* Description */}
                  <p className="text-xs sm:text-sm text-text-secondary leading-relaxed">
                    {item.description}
                  </p>

                  {/* Attached Supporting Evidence Badges */}
                  {item.evidenceList && item.evidenceList.length > 0 && (
                    <div className="bg-bg-surface p-3.5 rounded-xl border border-border-default space-y-2">
                      <p className="text-[11px] font-bold uppercase tracking-wider text-text-muted flex items-center gap-1.5">
                        <span>Supporting Verified Evidence</span>
                      </p>
                      <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
                        {item.evidenceList.map((ev, eIdx) => (
                          <div
                            key={eIdx}
                            className="p-2 rounded-lg bg-bg-surface-hover/60 border border-border-default/60 text-xs flex items-center justify-between gap-2"
                          >
                            <div className="truncate">
                              <span className="font-semibold text-text-primary block truncate">{ev.description}</span>
                              <span className="text-[10px] text-text-muted">Source: {ev.sourceModule}</span>
                            </div>
                            {ev.metricValue && (
                              <span className="text-[11px] font-mono font-bold text-brand-teal shrink-0 px-1.5 py-0.5 rounded bg-brand-teal/10">
                                {ev.metricValue}
                              </span>
                            )}
                          </div>
                        ))}
                      </div>
                    </div>
                  )}

                  {/* Recommended Action */}
                  {item.recommendedAction && (
                    <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pt-2 border-t border-border-default">
                      <div className="text-xs text-text-primary flex items-start gap-2">
                        <span className="text-brand-gold font-bold">Action:</span>
                        <span>{item.recommendedAction}</span>
                      </div>
                      {item.actionModule && (
                        <Button
                          variant="gold"
                          size="sm"
                          onClick={() => {
                            if (item.actionModule === 'LEARNING_HUB') {
                              window.location.href = '/learning';
                            } else if (item.actionModule === 'DSA_TRACKER') {
                              window.location.href = '/dsa';
                            } else if (item.actionModule === 'CAREER_HUB') {
                              window.location.href = '/career';
                            } else if (item.actionModule === 'KNOWLEDGE_HUB') {
                              window.location.href = '/knowledge-hub';
                            }
                          }}
                          className="shrink-0"
                        >
                          Execute Action →
                        </Button>
                      )}
                    </div>
                  )}
                </CardContent>
              </Card>
            );
          })}
        </div>
      )}
    </div>
  );
}
